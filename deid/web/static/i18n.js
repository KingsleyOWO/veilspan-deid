const LANG_KEY = 'veilspan-language';
let language = 'zh-TW';
const pageText = [];

function t(source, values = {}) {
  const message = language === 'en' && Object.hasOwn(EN, source) ? EN[source] : source;
  return message.replace(/\{(\w+)(?:, ([^,{}]+), ([^{}]+))?\}/g, (match, key, one, many) => {
    if (!Object.hasOwn(values, key)) return match;
    const value = values[key];
    return one ? `${value} ${value === 1 ? one : many}` : String(value);
  });
}

function detailText(source) {
  if (language !== 'en' || typeof source !== 'string') return source;
  if (Object.hasOwn(EN, source)) return EN[source];
  for (const [pattern, replace] of EN_DETAILS) {
    if (pattern.test(source)) return source.replace(pattern, replace);
  }
  return source;
}

function setLanguage(next) {
  language = next === 'en' ? 'en' : 'zh-TW';
  try { localStorage.setItem(LANG_KEY, language); } catch (e) { /* storage can be disabled */ }
  document.documentElement.lang = language === 'en' ? 'en' : 'zh-Hant';
  for (const { node, attribute, source } of pageText) {
    if (attribute) node.setAttribute(attribute, t(source));
    else node.textContent = t(source);
  }
  document.querySelector('#language').value = language;
}

function initLanguage() {
  for (const node of document.querySelectorAll('[data-i18n]')) {
    const attribute = node.dataset.i18n;
    pageText.push({ node, attribute, source: attribute ? node.getAttribute(attribute) : node.textContent });
  }
  for (const node of document.querySelectorAll('[data-i18n-title]')) {
    pageText.push({ node, attribute: 'title', source: node.title });
  }
  const requested = new URLSearchParams(location.search).get('lang');
  let stored;
  try { stored = localStorage.getItem(LANG_KEY); } catch (e) { /* storage can be disabled */ }
  setLanguage(requested === 'en' || requested === 'zh-TW' ? requested : stored);
}
